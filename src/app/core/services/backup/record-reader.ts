import { BackupIssue } from '../../models';

/** Stops the reading of a backup at the first problem: a file written by the app has none. */
export class BackupFormatError extends Error {
  constructor(readonly issue: BackupIssue) {
    super(`Invalid backup: ${issue.code}${issue.path ? ` at ${issue.path}` : ''}`);
    this.name = 'BackupFormatError';
  }
}

export function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * Reads the typed fields of one record of a backup. Each method returns a value of the right type
 * or throws with the path of the field, so a parsed record is valid by construction.
 */
export class RecordReader {
  constructor(
    private readonly record: Record<string, unknown>,
    private readonly path: string,
  ) {}

  /** Primary and foreign keys: positive integers, as generated by IndexedDB. */
  id(field: string): number {
    return this.integer(field, 1);
  }

  integer(field: string, min = 0): number {
    const value = this.record[field];
    return typeof value === 'number' && Number.isInteger(value) && value >= min
      ? value
      : this.fail(field);
  }

  number(field: string): number {
    const value = this.record[field];
    return typeof value === 'number' && Number.isFinite(value) && value >= 0
      ? value
      : this.fail(field);
  }

  /** Epoch milliseconds. */
  timestamp(field: string): number {
    return this.integer(field);
  }

  text(field: string): string {
    const value = this.record[field];
    return typeof value === 'string' ? value : this.fail(field);
  }

  boolean(field: string): boolean {
    const value = this.record[field];
    return typeof value === 'boolean' ? value : this.fail(field);
  }

  oneOf<T extends string | number>(field: string, allowed: readonly T[]): T {
    const value = this.record[field];
    return allowed.find((option) => option === value) ?? this.fail(field);
  }

  /** `null` is a valid value, e.g. the load of an exercise still to be tested. */
  nullable<T>(field: string, read: (field: string) => T): T | null {
    return this.record[field] === null ? null : read(field);
  }

  /** An absent field stays absent, so the restored record has exactly the keys of the original. */
  optional<K extends string, T>(field: K, read: (field: K) => T): Partial<Record<K, T>> {
    return this.record[field] === undefined ? {} : ({ [field]: read(field) } as Record<K, T>);
  }

  private fail(field: string): never {
    throw new BackupFormatError({ code: 'invalidRecord', path: `${this.path}.${field}` });
  }
}
